/*
  Temporary PostgreSQL development schema for LabDesk.
  Connect to an existing database before running this file; database creation
  is handled by the development environment, not by this schema script.
  Safe to run repeatedly; existing tables, rows and indexes are preserved.

  This mirrors sqlserver.sql. The shared unique index enforces scoped codes
  AND Reference versions (entity_kind='Reference', parent_id=Parameter id,
  code_key='VERSION:<number>').
*/

CREATE TABLE IF NOT EXISTS lab_entity (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_kind VARCHAR(40) NOT NULL,
    parent_id INTEGER NOT NULL DEFAULT 0,
    code_key TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_lab_entity_code
    ON lab_entity(entity_kind, parent_id, code_key) WHERE code_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_lab_entity_parent ON lab_entity(entity_kind, parent_id);
CREATE TABLE IF NOT EXISTS lab_audit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name VARCHAR(80) NOT NULL,
    entity_id INTEGER NOT NULL,
    action_name VARCHAR(40) NOT NULL,
    actor VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details TEXT NOT NULL
);