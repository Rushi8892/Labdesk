CREATE TABLE IF NOT EXISTS lab_entity (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_kind VARCHAR(40) NOT NULL,
    parent_id INTEGER NOT NULL DEFAULT 0,
    code_key TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_lab_entity_code ON lab_entity(entity_kind,parent_id,code_key) WHERE code_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_lab_entity_parent ON lab_entity(entity_kind,parent_id);
CREATE TABLE IF NOT EXISTS lab_audit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name VARCHAR(80) NOT NULL,
    entity_id INTEGER NOT NULL,
    action_name VARCHAR(40) NOT NULL,
    actor VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details TEXT NOT NULL
);